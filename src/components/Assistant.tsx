import { useEffect, useRef, useState } from 'react'
import { respond, resetContext, isInjection, Mode, Reply } from '../services/assistant/respond'
import { MODEL_SIZE_LABEL, webgpuSupported, loadEngine, generate } from '../services/local-ai'

type Msg = { role: 'user' | 'ai'; text: string; evidence?: Reply['evidence']; generated?: boolean }
type AI = { status: 'off' | 'confirm' | 'loading' | 'ready' | 'error'; progress: number; text: string }
const MODES: [Mode, string][] = [['recruiter', 'Recruiter'], ['technical', 'Technical'], ['casual', 'Casual'], ['interview', 'Interview']]
const SUGGESTED = [
  'What programming languages does Raynard know?', 'Tell me about his thesis project.', 'What was his role in AlgoRhythm?',
  'Does he have experience with computer vision?', 'What is his experience with databases?', 'How does he approach problem-solving?',
  'What makes him a suitable Software Engineering intern?', 'What areas is he currently improving?',
]
const WELCOME: Msg = { role: 'ai', text: "Hello! I'm Raynard's AI portfolio assistant. You can ask me about his technical background, projects, experience, working style, and career interests." }

export default function Assistant() {
  const [msgs, setMsgs] = useState<Msg[]>([WELCOME])
  const [input, setInput] = useState('')
  const [mode, setMode] = useState<Mode>('recruiter')
  const [busy, setBusy] = useState(false)
  const [ai, setAi] = useState<AI>({ status: 'off', progress: 0, text: '' })
  const [useLLM, setUseLLM] = useState(false)
  const engine = useRef<Awaited<ReturnType<typeof loadEngine>> | null>(null)
  const end = useRef<HTMLDivElement>(null)
  useEffect(() => { end.current?.scrollIntoView({ behavior: 'smooth', block: 'nearest' }) }, [msgs, busy])
  useEffect(() => () => engine.current?.worker.terminate(), [])

  const startLoad = () => {
    setAi({ status: 'loading', progress: 0, text: 'Starting…' })
    loadEngine((progress, text) => setAi({ status: 'loading', progress, text }))
      .then(e => { engine.current = e; setAi({ status: 'ready', progress: 1, text: '' }); setUseLLM(true) })
      .catch(err => setAi({ status: 'error', progress: 0, text: String(err?.message ?? err) }))
  }
  const cancel = () => { engine.current?.worker.terminate(); engine.current = null; setUseLLM(false); setAi({ status: 'off', progress: 0, text: '' }) }

  const ask = async (q: string) => {
    q = q.trim().slice(0, 300)
    if (!q || busy) return
    const history = msgs.filter(m => m !== WELCOME).map(m => ({ role: m.role === 'user' ? 'user' as const : 'assistant' as const, content: m.text }))
    setMsgs(m => [...m, { role: 'user', text: q }]); setInput(''); setBusy(true)
    let reply: Reply, generated = false
    if (useLLM && engine.current && !isInjection(q)) {
      try { reply = await generate(engine.current.engine, q, mode, history); generated = true }
      catch { reply = respond(q, mode) }
    } else {
      await new Promise(r => setTimeout(r, 450))
      reply = respond(q, mode)
    }
    setMsgs(m => [...m, { role: 'ai', text: reply.text, evidence: reply.evidence, generated }]); setBusy(false)
  }

  return (
    <div className="chat">
      <div className="chat-top">
        <div role="group" aria-label="Interaction mode" className="modes">
          {MODES.map(([k, l]) => <button key={k} aria-pressed={mode === k} className={mode === k ? 'on' : ''} onClick={() => setMode(k)}>{l}</button>)}
        </div>
        <button className="ghost" onClick={() => { resetContext(); setMsgs([WELCOME]) }}>Clear</button>
      </div>
      <p className="muted small">AI representative of Raynard, not Raynard himself. By default, answers come from a verified knowledge base (no LLM, nothing stored).</p>
      <div className="log" role="log" aria-live="polite">
        {msgs.map((m, i) => (
          <div key={i} className={'msg ' + m.role}>
            <div className="bubble">{m.text}</div>
            {m.generated && <span className="muted small">Generated by an on-device model from retrieved facts</span>}
            {m.role === 'ai' && i > 0 && <button className="ghost small" onClick={() => navigator.clipboard?.writeText(m.text)}>Copy</button>}
            {!!m.evidence?.length && (
              <details className="ev"><summary>Evidence ({m.evidence.length})</summary>
                <ul>{m.evidence.map(e => <li key={e.id}>{e.href ? <a href={e.href}>{e.label}</a> : <span className="muted">{e.label}</span>}</li>)}</ul>
              </details>)}
          </div>
        ))}
        {busy && <div className="msg ai"><div className="bubble typing" aria-label="Assistant is typing"><i /><i /><i /></div></div>}
        <div ref={end} />
      </div>
      {msgs.length === 1 && <div className="chips">{SUGGESTED.map(s => <button key={s} className="chip" onClick={() => ask(s)}>{s}</button>)}</div>}
      <div className="send">
        <input value={input} maxLength={300} aria-label="Ask a question about Raynard" placeholder="Ask about Raynard's projects, skills, experience…"
          onChange={e => setInput(e.target.value)} onKeyDown={e => e.key === 'Enter' && ask(input)} />
        <button className="btn primary" onClick={() => ask(input)} disabled={busy || !input.trim()}>Send</button>
      </div>
      <div className="aipanel">
        {ai.status === 'off' && (webgpuSupported()
          ? <button className="ghost" onClick={() => setAi({ ...ai, status: 'confirm' })}>Enable on-device AI (optional)</button>
          : <p className="muted small">On-device AI needs WebGPU, which this browser does not support. The knowledge assistant works as normal.</p>)}
        {ai.status === 'confirm' && <div className="panel">
          <p className="small">This downloads a language model (about {MODEL_SIZE_LABEL}) to your browser. It runs on your device, nothing you type is sent anywhere, and it is cached for next time.</p>
          <button className="btn primary" onClick={startLoad}>Download and enable</button>{' '}
          <button className="ghost" onClick={() => setAi({ ...ai, status: 'off' })}>No thanks</button></div>}
        {ai.status === 'loading' && <div className="panel"><progress value={ai.progress} max={1} aria-label="Model download progress" />
          <p className="small muted">{ai.text}</p><button className="ghost" onClick={cancel}>Cancel</button></div>}
        {ai.status === 'ready' && <label className="small"><input type="checkbox" checked={useLLM} onChange={e => setUseLLM(e.target.checked)} /> Use on-device AI for answers (falls back to the knowledge assistant if it fails)</label>}
        {ai.status === 'error' && <p className="small muted">The on-device AI could not start ({ai.text}). The knowledge assistant is still available.</p>}
      </div>
    </div>
  )
}
